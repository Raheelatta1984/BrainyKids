const DICTIONARIES: Partial<Record<LocaleCode, Dictionary>> = { es: ES, fr: FR, ar: AR, ur: UR, hi: HI, zh: ZH };

/** Looks up a phrase in the family's master language, falling back to English. */
export function t(
  locale: LocaleCode | string | undefined | null,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const dictionary = locale && locale !== "en" ? DICTIONARIES[locale as LocaleCode] : undefined;
  const template = dictionary?.[key] ?? EN[key] ?? key;
  return fill(template, vars);
}

export function fill(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole,
  );
}

/** English wording, used by the behavioural log and grown-up screens. */
export function tEn(key: MessageKey, vars?: Record<string, string | number>): string {
  return fill(EN[key] ?? key, vars);
}
